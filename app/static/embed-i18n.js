const DICTS = { az, ru, en };

export function pickLang(value) {
  const code = String(value || "").slice(0, 2).toLowerCase();
  return DICTS[code] ? code : "az";
}

export function strings(lang) {
  return DICTS[pickLang(lang)];
}
